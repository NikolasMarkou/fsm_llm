"""The state-kind registry changes nothing a caller can see (plan d454fd62, group A4).

Row 0.14 moves every completion and synthesize rule behind one registry. This
file is the safety net that stays green through the whole refactor and the later
layout split: it recomputes, on the current code, the record that
``kind_corpus.py`` stored for the parent code in
``fixtures/kind_equality_baseline.json`` (``fsm_id``, dump hashes, validator and
gate findings, loader refusals, the request bytes of three scripted turns) and
compares the two. The test only compares; the baseline is regenerated by hand
(``python -m tests.test_fsm_llm.kind_corpus --write``), never here, and a
failure is a behaviour change to explain, not a fixture to refresh.

Offline: the turns run on ``fsm_llm.testing`` doubles, nothing touches a network
or a model, and no test reads state another test leaves behind.
"""

from __future__ import annotations

import datetime
import json
from typing import Any

import pytest

from tests.test_fsm_llm import kind_corpus as kc

_BASELINE = kc.read_baseline()
_GROUPS = sorted({name.split("/", 1)[0] for name in _BASELINE["cases"]})
_SCENARIOS = sorted(_BASELINE["scenarios"])
_SHOWN = 300


@pytest.fixture(scope="module")
def current() -> dict[str, Any]:
    """The packed record of the code under test: cases, scenarios and schema facts."""
    cases = kc.corpus()
    return {
        "cases": {
            name: kc.pack_record(kc.describe(definition, options))
            for name, (definition, options) in cases.items()
        },
        "scenarios": kc.scenarios(),
        "schema": kc._plain(kc._schema_facts()),
    }


def _short(value: Any) -> str:
    text = json.dumps(value, sort_keys=True)
    return text if len(text) <= _SHOWN else text[:_SHOWN] + "..."


def _differences(expected: Any, actual: Any, where: str) -> list[str]:
    """Every leaf where *actual* differs from *expected*, one line each."""
    if isinstance(expected, dict) and isinstance(actual, dict):
        out: list[str] = []
        for key in sorted(expected.keys() | actual.keys()):
            if key not in actual:
                out.append(f"{where}/{key}: missing now (was {_short(expected[key])})")
            elif key not in expected:
                out.append(f"{where}/{key}: new (is {_short(actual[key])})")
            else:
                out += _differences(expected[key], actual[key], f"{where}/{key}")
        return out
    if expected == actual:
        return []
    return [f"{where}: was {_short(expected)}, is {_short(actual)}"]


class TestBaselineFile:
    def test_is_canonical_text(self):
        """UTF-8, ``\\n`` line ends, the layout the generator writes, no absolute path."""
        raw = kc.BASELINE_PATH.read_bytes()
        text = raw.decode("utf-8")
        assert b"\r" not in raw
        assert text.endswith("}\n")
        assert kc.dumps(json.loads(text)) == text
        assert str(kc.ROOT) not in text
        assert "/home/" not in text and "/media/" not in text

    def test_is_valid_json_with_the_three_sections(self):
        assert sorted(_BASELINE) == ["cases", "scenarios", "schema"]

    def test_names_the_same_cases_as_the_corpus(self, current: dict[str, Any]):
        assert sorted(current["cases"]) == sorted(_BASELINE["cases"])
        assert sorted(current["scenarios"]) == _SCENARIOS


class TestCorpusCoverage:
    """The corpus must keep covering what the refactor touches."""

    def test_holds_every_example_fsm(self):
        files = [n for n in _BASELINE["cases"] if n.startswith("file/examples/")]
        assert len(files) == 14

    def test_holds_the_bench_fsms(self):
        hand = [n for n in _BASELINE["cases"] if n.startswith("bench/hand/")]
        host = [n for n in _BASELINE["cases"] if n.startswith("bench/host/")]
        assert (len(hand), len(host)) == (16, 16)

    def test_holds_every_reasoning_fsm(self):
        from fsm_llm.reasoning.strategy_files import FSM_NAMES

        reasoning = {
            n.split("/", 1)[1] for n in _BASELINE["cases"] if n.startswith("reasoning/")
        }
        assert reasoning == set(FSM_NAMES)

    def test_holds_both_non_default_kinds_and_their_refusals(self):
        kinds = {
            kind
            for record in _BASELINE["cases"].values()
            for kind in record.get("state_kinds", {}).values()
        }
        assert kinds == {"completion", "synthesize"}
        refused = [r for r in _BASELINE["cases"].values() if r["loads"] is False]
        assert len(refused) >= 10
        assert all(r["load_errors"] for r in refused)

    def test_loaded_states_of_every_builder_have_a_kind(self):
        """native_fc and the meta builder ship completion states."""
        for name in ("builder/agents/native-fc", "builder/agents/meta-builder"):
            assert "completion" in _BASELINE["cases"][name]["state_kinds"].values()

    def test_scenarios_record_request_bytes(self):
        for name, scenario in _BASELINE["scenarios"].items():
            requests = scenario["requests"]
            assert requests, name
            assert all(r["bytes"] > 0 and len(r["sha256"]) == 64 for r in requests)


class TestEqualityWithTheParentCode:
    @pytest.mark.parametrize("group", _GROUPS)
    def test_cases_match(self, current: dict[str, Any], group: str):
        problems: list[str] = []
        for name, expected in _BASELINE["cases"].items():
            if name.split("/", 1)[0] == group and name in current["cases"]:
                problems += _differences(expected, current["cases"][name], name)
        assert not problems, "\n".join(problems)

    @pytest.mark.parametrize("scenario", _SCENARIOS)
    def test_scenario_matches(self, current: dict[str, Any], scenario: str):
        problems = _differences(
            _BASELINE["scenarios"][scenario], current["scenarios"][scenario], scenario
        )
        assert not problems, "\n".join(problems)

    def test_the_day_never_reaches_a_scenario(self, monkeypatch: pytest.MonkeyPatch):
        """The extraction prompt names today's date: the scenarios freeze the clock."""
        real = datetime.date

        class _OtherDay(real):  # type: ignore[misc, valid-type]
            @classmethod
            def today(cls) -> datetime.date:
                return real(2000, 1, 1)

        monkeypatch.setattr(datetime, "date", _OtherDay)
        assert datetime.date.today() == real(2000, 1, 1)
        problems = _differences(
            _BASELINE["scenarios"]["plain"], kc.scenarios()["plain"], "plain"
        )
        assert not problems, "\n".join(problems)

    def test_schema_facts_match(self, current: dict[str, Any]):
        """``kind`` is no field, no schema property: the dump and ``fsm_id`` cannot move."""
        assert not _differences(_BASELINE["schema"], current["schema"], "schema")
        assert "kind" not in current["schema"]["state_fields"]
        assert "kind" not in current["schema"]["state_schema_properties"]


class TestHelpers:
    def test_stable_info_sorts_joined_lists_and_lines(self):
        lines = ["Terminal states: c, b", "A line", "Reachable terminal states: z, a"]
        assert kc._stable_info(lines) == [
            "A line",
            "Reachable terminal states: a, z",
            "Terminal states: b, c",
        ]

    def test_pack_inlines_short_values_and_hashes_long_ones(self):
        assert kc.pack(["a", ("b",)]) == ["a", ["b"]]
        long = ["x" * 50] * 20
        assert kc.pack(long) == {"count": 20, "sha256": kc._sha(kc._canonical(long))}

    def test_differences_name_the_leaf(self):
        got = _differences({"a": {"b": 1}}, {"a": {"b": 2}, "c": 3}, "case")
        assert got == ["case/a/b: was 1, is 2", "case/c: new (is 3)"]

    def test_the_corpus_is_built_fresh_every_time(self):
        first = kc.corpus()
        name = next(iter(first))
        first[name][0]["name"] = "mutated"
        assert kc.corpus()[name][0]["name"] != "mutated"
